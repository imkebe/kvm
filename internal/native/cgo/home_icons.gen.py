#!/usr/bin/env python3
"""Generates home_icons.c: the icons of the home screen's function list.

The icons are the 20 px solid Heroicons (MIT licence) that the web UI uses,
read from ui/node_modules, and a keyboard and an Ethernet socket drawn here. Each becomes an 18 px
alpha-only LVGL image, which the screen colours by state. Needs rsvg-convert.
Run from this directory: python3 home_icons.gen.py
"""
import re, struct, subprocess, zlib
from pathlib import Path

SIZE = 18
HERO = Path("../../../ui/node_modules/@heroicons/react/20/solid")
KEYBOARD = (
    '<path fill-rule="evenodd" clip-rule="evenodd" d="M3 4.5A2 2 0 0 0 1 6.5v7a2 2 0 0 0 2 2h14a2 2 0 0 0 2-2v-7a2 2 0 0 0-2-2H3Z'
    "M4 7.5h1.5V9H4V7.5Zm3 0h1.5V9H7V7.5Zm3 0h1.5V9H10V7.5Zm3 0h1.5V9H13V7.5Zm3 0h0V9h0V7.5Z"
    'M4 10h1.5v1.5H4V10Zm3 0h1.5v1.5H7V10Zm3 0h1.5v1.5H10V10Zm3 0h3v1.5h-3V10ZM6 12.75h8v1.25H6v-1.25Z"/>'
)
# An Ethernet socket seen from the front: the opening and its four contacts.
ETHERNET = (
    '<path fill-rule="evenodd" clip-rule="evenodd" d="M4 3A2 2 0 0 0 2 5v10a2 2 0 0 0 2 2h12a2 2 0 0 0 2-2V5a2 2 0 0 0-2-2H4Z'
    "M5 6.5h10v5.5h-2.5v2.5h-5V12H5V6.5Z"
    'M6.4 6.5h1.1v2.4H6.4V6.5Zm2.1 0h1.1v2.4H8.5V6.5Zm2.1 0h1.1v2.4h-1.1V6.5Zm2.1 0h1.1v2.4h-1.1V6.5Z"/>'
)
# Chip name on the Go side, C name, and the Heroicon, or the SVG drawn here.
ICONS = [
    ("KBD", "keyboard", KEYBOARD),
    ("ABS", "mouse_abs", "CursorArrowRaysIcon"),
    ("REL", "mouse_rel", "CursorArrowRippleIcon"),
    ("DISK", "disk", "CircleStackIcon"),
    ("AUD", "speaker", "SpeakerWaveIcon"),
    ("MIC", "microphone", "MicrophoneIcon"),
    ("CAM", "camera", "CameraIcon"),
    ("SER", "serial", "CommandLineIcon"),
    ("NET", "network", ETHERNET),
    ("OSS", "services", "ComputerDesktopIcon"),
    ("VID", "video", "TvIcon"),
]


def heroicon(name):
    text = (HERO / (name + ".js")).read_text()
    paths = []
    for block in re.findall(r'createElement\("path", \{(.*?)\}\)', text, re.S):
        attrs = dict(re.findall(r'(\w+): "([^"]*)"', block))
        rule = ' fill-rule="evenodd" clip-rule="evenodd"' if "fillRule" in attrs else ""
        paths.append('<path%s d="%s"/>' % (rule, attrs["d"]))
    return "".join(paths)


def alpha(svg_body):
    svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 20 20" fill="#fff">%s</svg>' % svg_body
    png = subprocess.run(["rsvg-convert", "-w", str(SIZE), "-h", str(SIZE)], input=svg.encode(), capture_output=True, check=True).stdout
    pos, data, width, height = 8, b"", 0, 0
    while pos < len(png):
        length, kind = struct.unpack(">I4s", png[pos : pos + 8])
        chunk = png[pos + 8 : pos + 8 + length]
        if kind == b"IHDR":
            width, height, depth, colour = struct.unpack(">IIBB", chunk[:10])
            assert (width, height, depth, colour) == (SIZE, SIZE, 8, 6), (width, height, depth, colour)
        elif kind == b"IDAT":
            data += chunk
        pos += 12 + length
    raw, stride, rows, prev = zlib.decompress(data), SIZE * 4, [], bytes(SIZE * 4)
    for y in range(height):
        f, line = raw[y * (stride + 1)], bytearray(raw[y * (stride + 1) + 1 : (y + 1) * (stride + 1)])
        for i in range(stride):
            a = line[i - 4] if i >= 4 else 0
            b = prev[i]
            c = prev[i - 4] if i >= 4 else 0
            if f == 1:
                line[i] = (line[i] + a) & 255
            elif f == 2:
                line[i] = (line[i] + b) & 255
            elif f == 3:
                line[i] = (line[i] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        rows.append(bytes(line[3::4]))
        prev = bytes(line)
    return rows


out = ["// Generated by home_icons.gen.py, do not edit it manually.", '#include "home_icons.h"', ""]
for _, name, hero in ICONS:
    rows = alpha(hero if hero.startswith("<") else heroicon(hero))
    out.append("static const uint8_t %s_map[] = {" % name)
    out += ["    " + ",".join(str(v) for v in row) + "," for row in rows]
    out.append("};")
    out.append(
        "static const lv_image_dsc_t %s_image = {.header.magic = LV_IMAGE_HEADER_MAGIC, .header.cf = LV_COLOR_FORMAT_A8, "
        ".header.w = %d, .header.h = %d, .header.stride = %d, .data_size = sizeof(%s_map), .data = %s_map};" % (name, SIZE, SIZE, SIZE, name, name)
    )
    out.append("")
out.append("const home_icon_t home_icons[] = {")
out += ['    {"%s", &%s_image},' % (chip, name) for chip, name, _ in ICONS]
out += ["};", "const int home_icons_size = sizeof(home_icons) / sizeof(home_icons[0]);", ""]
Path("home_icons.c").write_text("\n".join(out))
print("home_icons.c has been generated")
